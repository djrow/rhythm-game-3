import { pitchNameToMidi } from './audioMath';
import type { EnsembleScore, ScoreNote } from './types';

function makeNotes(
  partPrefix: string,
  sequence: Array<[string, number, number, ('p' | 'mp' | 'mf' | 'f')?]>
): ScoreNote[] {
  return sequence.map(([pitch, startBeat, durationBeats, dynamics], idx) => ({
    id: `${partPrefix}-${idx}`,
    pitch,
    midi: pitchNameToMidi(pitch),
    startBeat,
    durationBeats,
    dynamics: dynamics ?? 'mf',
  }));
}

